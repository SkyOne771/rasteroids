#!/usr/bin/env python3
"""Generate source-derived reference documentation; --check rejects stale output."""
import argparse
import ast
import hashlib
from html.parser import HTMLParser
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = '<!-- BEGIN GENERATED FACTS -->', '<!-- END GENERATED FACTS -->'


class Buttons(HTMLParser):
    def __init__(self):
        super().__init__()
        self.controls = []

    def handle_starttag(self, tag, attributes):
        values = dict(attributes)
        if tag == 'button' and values.get('id', '').startswith('touch-'):
            self.controls.append((values['id'], values.get('aria-label', '')))


def source_files():
    roots = ['server.py', 'index.html', 'web.css', 'account.js', 'assets/icon.svg', 'deploy/Caddyfile', 'package.json', 'package-lock.json', 'version.json']
    paths = [ROOT / name for name in roots if (ROOT / name).is_file()]
    extensions = {'.py', '.js', '.cjs', '.mjs', '.css', '.html', '.json', '.yml', '.sh', '.service', '.timer'}
    for directory in ['scripts', 'tests', 'deploy', '.github']:
        paths += [path for path in (ROOT / directory).rglob('*') if path.is_file() and path.suffix in extensions]
    return sorted(paths)


def generate(root=ROOT):
    source = (root / 'server.py').read_text()
    tree = ast.parse(source)
    routes = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.If):
            continue
        paths, methods = [], []
        for comparison in ast.walk(node.test):
            if not isinstance(comparison, ast.Compare) or not isinstance(comparison.left, ast.Name):
                continue
            if comparison.left.id == 'path':
                right = comparison.comparators[0]
                if isinstance(comparison.ops[0], ast.Eq) and isinstance(right, ast.Constant):
                    paths.append(right.value)
                elif isinstance(comparison.ops[0], ast.In) and isinstance(right, ast.Tuple):
                    paths += [value.value for value in right.elts if isinstance(value, ast.Constant)]
            if comparison.left.id == 'method' and isinstance(comparison.ops[0], ast.Eq):
                methods.append(comparison.comparators[0].value)
        for path in paths:
            if isinstance(path, str) and path.startswith('/api/'):
                routes.add((methods[0] if methods else 'POST', path))
    flags = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute) or node.func.attr != 'add_argument':
            continue
        flag = node.args[0].value
        default = next((item.value for item in node.keywords if item.arg == 'default'), None)
        env, fallback = '—', 'unset'
        for call in ast.walk(default) if default else []:
            if isinstance(call, ast.Call) and ast.unparse(call.func) == 'os.environ.get':
                env = call.args[0].value
                if len(call.args) > 1:
                    fallback = str(call.args[1].value)
        if any(item.arg == 'action' and isinstance(item.value, ast.Constant) and item.value.value == 'store_true' for item in node.keywords):
            fallback = 'false (set environment variable to 1 to enable)'
        flags.append((flag, env, fallback))
    schema = next(node.value.value for node in tree.body if isinstance(node, ast.Assign) and any(isinstance(target, ast.Name) and target.id == 'SCHEMA' for target in node.targets))
    parser = Buttons(); parser.feed((root / 'index.html').read_text())
    digest = hashlib.sha256()
    for path in source_files():
        digest.update(path.relative_to(ROOT).as_posix().encode() + b'\0' + path.read_bytes() + b'\0')
    tables = []
    with sqlite3.connect(':memory:') as db:
        db.executescript(schema)
        for (name,) in db.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name"):
            columns = ', '.join(f'`{column[1]}` {column[2]}' for column in db.execute(f'PRAGMA table_info({name})'))
            tables.append((name, columns))
    lines = ['# Generated interface reference', '', 'Generated by `python3 scripts/generate_docs.py`. Do not edit this file by hand.', '', '## HTTP API', '', '| Method | Path |', '| --- | --- |']
    lines += [f'| `{method}` | `{path}` |' for method, path in sorted(routes)]
    lines += ['', '## Server configuration', '', '| Flag | Environment variable | Default |', '| --- | --- | --- |']
    lines += [f'| `{flag}` | `{env}` | {default} |' for flag, env, default in flags]
    lines += ['', 'An unset database path uses `data/rasteroids.sqlite3`. Production data is configured outside the source directory.', '', '## Touch controls', '', '| Element | Action |', '| --- | --- |']
    lines += [f'| `{identifier}` | {label} |' for identifier, label in parser.controls]
    lines += ['', '## SQLite schema', '', '| Table | Columns |', '| --- | --- |']
    lines += [f'| `{name}` | {columns} |' for name, columns in tables]
    lines += ['', '## Documentation freshness', '', 'SHA-256 of application, test, deployment, tooling, and workflow source:', '', f'`{digest.hexdigest()}`', '', 'CI runs this generator in check mode. Any changed source requires regenerating this reference in the same commit.', '']
    summary = f'{BEGIN}\n**Source-derived interface:** {len(routes)} API routes · {len(tables)} SQLite tables · {len(parser.controls)} touch controls · {len(flags)} server options. [Full generated reference](docs/REFERENCE.md).\n{END}'
    readme = (root / 'README.md').read_text()
    if BEGIN not in readme or END not in readme:
        raise RuntimeError('README generated section markers are missing.')
    readme = re.sub(re.escape(BEGIN) + r'[\s\S]*?' + re.escape(END), lambda _: summary, readme)
    return {root / 'docs/REFERENCE.md': '\n'.join(lines), root / 'README.md': readme}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, expected in generate().items():
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if stale:
        raise SystemExit('Stale documentation: ' + ', '.join(stale) + '. Run npm run docs and commit the results.')
    print('Generated documentation is current.' if args.check else 'Updated README facts and docs/REFERENCE.md.')
